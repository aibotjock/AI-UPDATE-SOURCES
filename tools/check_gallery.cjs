const {chromium}=require('playwright');
const fs=require('fs');
const path=require('path');
(async()=>{
 const repo=path.resolve(__dirname,'..');
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1920,height:1080}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('file://'+path.join(repo,'library/gallery.html'));
 await page.waitForSelector('.card');
 const initial=await page.locator('.card').count();
 if(initial!==60)throw Error('Expected first page of 60 cards');
 await page.locator('#category').selectOption('logo');
 const logos=await page.locator('.card').count();if(logos!==40)throw Error('Expected 40 logos');
 await page.locator('#q').fill('Claude');
 if(await page.locator('.card').count()<1)throw Error('Claude search returned no logo');
 await page.locator('#q').fill('');await page.locator('#category').selectOption('sound-effect');
 const sounds=await page.locator('audio').count();if(sounds!==60)throw Error('Expected 60 audio controls');
 await page.locator('#category').selectOption('');
 await page.locator('#q').fill('definitely-no-matching-asset-123456');
 if(await page.locator('.card').count()!==0)throw Error('Empty search not handled');
 await page.locator('#q').fill('');await page.locator('#category').selectOption('logo');
 await page.screenshot({path:path.join(repo,'library/gallery-preview.png'),fullPage:false});
 await page.setViewportSize({width:390,height:844});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
 if(overflow)throw Error('Mobile gallery overflows');
 if(errors.length)throw Error(errors.join('; '));
 const report={initial_cards:initial,logos,sound_controls:sounds,search:'passed',mobile_overflow:false,page_errors:errors};
 fs.writeFileSync(path.join(repo,'library/gallery-verification.json'),JSON.stringify(report,null,2)+'\n');
 console.log(JSON.stringify(report));await browser.close();
})().catch(e=>{console.error(e.message);process.exit(1)});
